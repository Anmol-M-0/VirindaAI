from __future__ import annotations

from collections.abc import Iterable, Iterator
from typing import Protocol

from virinda.domain.events import AssistantEvent
from virinda.domain.models import Message, ProviderRequest, Session


class CompletionProvider(Protocol):
    name: str

    def stream(self, request: ProviderRequest) -> Iterator[str]: ...


class ProviderRouter(Protocol):
    def select(self, request: ProviderRequest) -> CompletionProvider: ...
    def available(self) -> tuple[str, ...]: ...


class ConversationStore(Protocol):
    def ensure_session(self, session: Session) -> None: ...
    def append_message(self, session_id: str, message: Message) -> None: ...
    def append_event(self, session_id: str, event: AssistantEvent) -> None: ...
    def load_messages(self, session_id: str) -> list[Message]: ...
    def list_sessions(self) -> list[str]: ...
    def load_latest_session(self) -> Session | None: ...
    def load_events(self, session_id: str, limit: int = 100) -> list[AssistantEvent]: ...
    def health(self) -> dict[str, object]: ...
    def backup(self, destination): ...
    def close(self) -> None: ...


class CancelToken(Protocol):
    generation_id: int

    def is_current(self, generation_id: int) -> bool: ...


class SentenceTokenizer(Protocol):
    def feed(self, chunk: str) -> Iterable[str]: ...
    def flush(self) -> Iterable[str]: ...
